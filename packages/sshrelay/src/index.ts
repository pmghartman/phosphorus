// `ssh <host>` from any host's terminal, one Host per tailnet peer in
// state/ssh_config, the hosts' own sshd reached straight over the tailnet
import { writeFileSync } from "node:fs";
import { isIPv4, lockACL } from "@phosphorus/util";

// a tailnet peer for ssh_config
export type Peer = { host: string; ip: string };

// one Host per tailnet peer
export function config(peers: Peer[]): string {
  let out = "# auto-generated by the frontend, do not edit, changes are overwritten\n";
  for (const p of peers) if (isIPv4(p.ip)) out += `\nHost ${p.host}\n\tHostName ${p.ip}\n`;
  return out;
}

let lastConfig = "";

// only on a change, throwing when the file can't be written
export function writeConfig(file: string, peers: Peer[]) {
  const text = config(peers);
  if (text === lastConfig) return;
  writeFileSync(file, text, { mode: 0o644 });
  // Windows OpenSSH refuses an included config others can write
  lockACL(file, true);
  lastConfig = text;
}
