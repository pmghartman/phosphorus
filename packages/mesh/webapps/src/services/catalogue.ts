// a volume's name from its path in the container
const volName = (p: string) => p.replace(/^\/+/, "").replace(/[^a-zA-Z0-9]+/g, "-");

// the compose file: the app on the host's tailnet address alone, data in named volumes
export function composeOf(s: Spec): string {
  const lines = ["services:", "  app:", `    image: ${s.image}`, "    restart: unless-stopped"];
  lines.push("    ports:", `      - "\${IP}:\${PORT}:${s.web}"`);
  for (const p of s.ports ?? []) lines.push(`      - "${p}"`);
  const env = Object.entries(s.env ?? {});
  if (env.length) {
    lines.push("    environment:");
    for (const [k, v] of env) lines.push(`      ${k}: "${v}"`);
  }
  if (s.vols?.length) {
    lines.push("    volumes:");
    for (const v of s.vols) lines.push(`      - ${volName(v)}:${v}`);
  }
  for (const m of s.more ?? []) lines.push(`    ${m}`);
  let text = lines.join("\n") + "\n" + (s.beside ?? "");
  const named = [
    ...(s.vols ?? []).map(volName),
    ...[...(s.beside ?? "").matchAll(/^\s+- ([a-z0-9-]+):\//gm)].map((m) => m[1]!),
  ];
  if (named.length) text += "volumes:\n" + named.map((n) => `  ${n}:\n`).join("");
  return text;
}

