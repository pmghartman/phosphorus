'use strict';
// `ssh <host>` from any host's terminal: Linux hosts straight over tailscale0,
// Docker Desktop and OrbStack hosts through this container, their sshd relayed in

const fs = require('fs');
const net = require('net');

const HOST_SSH_HOST = process.env.HOST_SSH_HOST || '127.0.0.1';
const HOST_SSH_PORT = Number(process.env.HOST_SSH_PORT || 22);
const RETRY_MS = 10000;
// the image's own path, run by the host through docker exec
const SELF = '/opt/frontend/ssh-relay.js';

// host.docker.internal: the host another machine as far as tailscale0 goes
const HOST_APART = !/^(127\.|localhost$)/.test(HOST_SSH_HOST);

function pipeBoth(a, b) {
  a.on('error', () => b.destroy());
  b.on('error', () => a.destroy());
  a.pipe(b).pipe(a);
}

// tailnet IP :22 -> the host's sshd, never on Linux, sshd already answering
// there, a bind of ours locking it out of its own port
function createSshInbound(note) {
  let server = null;
  let boundIp = '';
  let failedAt = 0;

  function bind(ip) {
    if (!HOST_APART) return;
    if (ip === boundIp && (server || Date.now() - failedAt < RETRY_MS)) return;
    if (server) { server.close(); server = null; }
    boundIp = ip;
    if (!ip) return;
    const s = net.createServer((c) => pipeBoth(c, net.connect(HOST_SSH_PORT, HOST_SSH_HOST)));
    s.on('error', (err) => {
      note('ssh', `can't relay ssh on ${ip}:22 to the host, retrying: ${err.message}`);
      if (server === s) { server = null; failedAt = Date.now(); }
      s.close();
    });
    s.listen(22, ip, () => note('ssh', `relaying ssh on ${ip}:22 to ${HOST_SSH_HOST}:${HOST_SSH_PORT}`));
    server = s;
  }

  return { bind };
}

// included by the host's ssh_config, one Host per tailnet peer
function sshConfig(peers) {
  let out = '# auto-generated by the frontend, do not edit, changes are overwritten\n';
  for (const p of peers) {
    if (!/^\d+\.\d+\.\d+\.\d+$/.test(p.ip)) continue;
    out += `\nHost ${p.host}\n\tHostName ${p.ip}\n`;
    if (HOST_APART) out += `\tProxyCommand docker exec -i hesperus node ${SELF} %h %p\n`;
  }
  return out;
}

// written only on a change, state/ the host's own directory
let lastConfig = '';
function writeSshConfig(file, peers) {
  const text = sshConfig(peers);
  if (text === lastConfig) return;
  fs.writeFileSync(file, text, { mode: 0o644 });
  lastConfig = text;
}

module.exports = { createSshInbound, writeSshConfig };

// ProxyCommand end: stdin/stdout <-> <ip>:<port>
if (require.main === module) {
  const s = net.connect(Number(process.argv[3]), process.argv[2]);
  process.stdin.pipe(s).pipe(process.stdout);
  s.on('error', (err) => { process.stderr.write(`${err.message}\n`); process.exit(1); });
  s.on('close', () => process.exit(0));
}
