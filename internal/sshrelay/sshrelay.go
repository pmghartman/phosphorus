// Package sshrelay: `ssh <host>` from any host's terminal, Linux hosts straight
// over tailscale0, Docker Desktop and OrbStack hosts through this container
package sshrelay

import (
	"fmt"
	"io"
	"net"
	"os"
	"regexp"
	"strconv"
	"sync"

	"github.com/pmghartman/phosphorus/internal/util"
)

const retryMS = 10000

var (
	hostSSHHost = util.Env("HOST_SSH_HOST", "127.0.0.1")
	hostSSHPort = util.EnvInt("HOST_SSH_PORT", 22)
	hostApart   = !regexp.MustCompile(`^(127\.|localhost$)`).MatchString(hostSSHHost)
)

func pipeBoth(a, b net.Conn) {
	go func() { io.Copy(b, a); b.Close(); a.Close() }()
	io.Copy(a, b)
	a.Close()
	b.Close()
}

// Inbound tailnet IP :22 -> the host's sshd, never on Linux
type Inbound struct {
	note     func(string, string)
	mu       sync.Mutex
	ln       net.Listener
	boundIP  string
	failedAt int64
}

// NewInbound with mesh's note
func NewInbound(note func(string, string)) *Inbound { return &Inbound{note: note} }

// Bind every tick, rebinding on a change
func (s *Inbound) Bind(ip string) {
	if !hostApart {
		return
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	if ip == s.boundIP && (s.ln != nil || util.Now()-s.failedAt < retryMS) {
		return
	}
	if s.ln != nil {
		s.ln.Close()
		s.ln = nil
	}
	s.boundIP = ip
	if ip == "" {
		return
	}
	ln, err := net.Listen("tcp", net.JoinHostPort(ip, "22"))
	if err != nil {
		s.note("ssh", fmt.Sprintf("can't relay ssh on %s:22 to the host, retrying: %v", ip, err))
		s.failedAt = util.Now()
		return
	}
	s.note("ssh", fmt.Sprintf("relaying ssh on %s:22 to %s:%d", ip, hostSSHHost, hostSSHPort))
	s.ln = ln
	go func() {
		for {
			c, err := ln.Accept()
			if err != nil {
				return
			}
			go func() {
				up, err := net.Dial("tcp", net.JoinHostPort(hostSSHHost, strconv.Itoa(hostSSHPort)))
				if err != nil {
					c.Close()
					return
				}
				pipeBoth(c, up)
			}()
		}
	}()
}

// Peer a tailnet peer for ssh_config
type Peer struct {
	Host string
	IP   string
}

// Config one Host per tailnet peer
func Config(peers []Peer) string {
	out := "# auto-generated by the frontend, do not edit, changes are overwritten\n"
	for _, p := range peers {
		if !util.IsIPv4(p.IP) {
			continue
		}
		out += fmt.Sprintf("\nHost %s\n\tHostName %s\n", p.Host, p.IP)
		if hostApart {
			out += "\tProxyCommand docker exec -i phosphorus phosphorus ssh-relay %h %p\n"
		}
	}
	return out
}

var (
	cfgMu      sync.Mutex
	lastConfig string
)

// WriteConfig only on a change
func WriteConfig(file string, peers []Peer) error {
	text := Config(peers)
	cfgMu.Lock()
	defer cfgMu.Unlock()
	if text == lastConfig {
		return nil
	}
	if err := os.WriteFile(file, []byte(text), 0o644); err != nil {
		return err
	}
	lastConfig = text
	return nil
}

// ProxyMain the ProxyCommand end: stdin/stdout <-> host:port
func ProxyMain(args []string) int {
	if len(args) < 2 {
		fmt.Fprintln(os.Stderr, "usage: phosphorus ssh-relay <host> <port>")
		return 2
	}
	c, err := net.Dial("tcp", net.JoinHostPort(args[0], args[1]))
	if err != nil {
		fmt.Fprintln(os.Stderr, err.Error())
		return 1
	}
	go func() {
		io.Copy(c, os.Stdin)
		if tc, ok := c.(*net.TCPConn); ok {
			tc.CloseWrite()
		}
	}()
	io.Copy(os.Stdout, c)
	return 0
}
