// Package sshrelay: `ssh <host>` from any host's terminal, one Host per tailnet
// peer in state/ssh_config, the hosts' own sshd reached straight over the tailnet
package sshrelay

import (
	"fmt"
	"os"
	"sync"

	"github.com/pmghartman/phosphorus/internal/util"
)

// Peer a tailnet peer for ssh_config
type Peer struct {
	Host string
	IP   string
}

// Config one Host per tailnet peer
func Config(peers []Peer) string {
	out := "# auto-generated by the frontend, do not edit, changes are overwritten\n"
	for _, p := range peers {
		if !util.IsIPv4(p.IP) {
			continue
		}
		out += fmt.Sprintf("\nHost %s\n\tHostName %s\n", p.Host, p.IP)
	}
	return out
}

var (
	cfgMu      sync.Mutex
	lastConfig string
)

// WriteConfig only on a change
func WriteConfig(file string, peers []Peer) error {
	text := Config(peers)
	cfgMu.Lock()
	defer cfgMu.Unlock()
	if text == lastConfig {
		return nil
	}
	if err := os.WriteFile(file, []byte(text), 0o644); err != nil {
		return err
	}
	lastConfig = text
	return nil
}
