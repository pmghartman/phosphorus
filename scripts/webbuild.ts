// webbuild: web/ into packages/webstatic/dist, the client bundled by Bun from
// the workspace's pinned packages (patches/ put in by bun install), every text
// file precompressed, and a manifest module naming each file so bun build
// --compile embeds them
import { gzipSync } from "bun";
import { mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { basename, dirname, extname, join, relative } from "node:path";
import { load } from "@phosphorus/theme";

const src = process.argv[2] ?? "web";
const out = process.argv[3] ?? "packages/webstatic/dist";
const modules = join(src, "node_modules");
const log = (s: string) => console.log(`[webbuild] ${s}`);

rmSync(out, { recursive: true, force: true });
mkdirSync(join(out, "vendor"), { recursive: true });

const write = (rel: string, data: Uint8Array | string) => {
  mkdirSync(dirname(join(out, rel)), { recursive: true });
  writeFileSync(join(out, rel), data);
};
const short = (data: Uint8Array) => new Bun.CryptoHasher("sha256").update(data).digest("hex").slice(0, 12);

// vendor files outside the bundle: fonts as they are, the rest hashed
const assets: Record<string, string> = {};
const hashed = (from: string, name: string) => {
  const data = readFileSync(from);
  const ext = extname(name);
  const rel = `vendor/h/${name.slice(0, -ext.length)}-${short(data)}${ext}`;
  write(rel, data);
  return "/" + rel;
};
assets["xterm.css"] = hashed(join(modules, "@xterm/xterm/css/xterm.css"), "xterm.css");
// katex's css beside its fonts, the folder named by the css's hash
const kcss = readFileSync(join(modules, "katex/dist/katex.min.css"));
const kdir = `vendor/h/katex-${short(kcss)}`;
for (const f of readdirSync(join(modules, "katex/dist/fonts"))) if (f.endsWith(".woff2")) write(`${kdir}/fonts/${f}`, readFileSync(join(modules, "katex/dist/fonts", f)));
write(`${kdir}/katex.css`, kcss);
assets["katex.css"] = `/${kdir}/katex.css`;

const res = await Bun.build({
  entrypoints: [join(src, "src/main.ts"), join(src, "style.css")],
  outdir: join(out, "assets"),
  naming: { entry: "[name]-[hash].[ext]", chunk: "[name]-[hash].[ext]", asset: "[name]-[hash].[ext]" },
  format: "esm",
  target: "browser",
  splitting: true,
  minify: true,
  sourcemap: "none",
  external: ["/vendor/*"],
  define: { __ASSETS__: JSON.stringify(assets) },
  loader: { ".md": "text" },
  plugins: [
    {
      // the theme library's tokens as CSS, the first thing style.css imports
      name: "phosphorus-themes",
      setup(b) {
        b.onResolve({ filter: /^phosphorus:themes$/ }, () => ({ path: "themes.css", namespace: "phosphorus-themes" }));
        b.onLoad({ filter: /.*/, namespace: "phosphorus-themes" }, () => ({ contents: load().css(), loader: "css" }));
      },
    },
  ],
});
for (const l of res.logs) console.error(String(l));
if (!res.success) process.exit(1);

// the page: its entry and style put in
const entry: Record<string, string> = {};
// main.ts is the one entry-point; style.css comes out as an asset
for (const o of res.outputs) {
  const name = basename(o.path).replace(/-[a-z0-9]+(\.\w+)$/, "$1");
  if (o.kind === "entry-point" || (o.kind === "asset" && name === "style.css")) entry[name] = "/" + relative(out, o.path).replaceAll("\\", "/");
}
let html = readFileSync(join(src, "index.html"), "utf8");
html = html.replace(`href="/style.css"`, `href="${entry["style.css"]}"`).replace(`<script type="module" src="/src/main.ts"></script>`, `<script type="module" src="${entry["main.js"]}"></script>`);
if (!entry["main.js"] || !entry["style.css"] || !html.includes(entry["main.js"]) || !html.includes(entry["style.css"])) {
  console.error("index.html lost its style.css or main.js tag");
  process.exit(1);
}
write("index.html", html);
for (const f of walk(join(src, "static"))) write(relative(join(src, "static"), f), readFileSync(f));

// precompressed as .gz, a hashed file's raw copy then dropped
const hashedPath = (rel: string) => rel.startsWith("assets/") || rel.startsWith("vendor/h/");
let n = 0;
for (const f of walk(out)) {
  const rel = relative(out, f).replaceAll("\\", "/");
  if (!/\.(js|css|html|svg|json|txt|map)$/.test(rel)) continue;
  const data = readFileSync(f);
  const gz = gzipSync(data, { level: 9 });
  if (gz.length >= data.length) continue;
  writeFileSync(f + ".gz", gz);
  if (hashedPath(rel)) rmSync(f);
  n++;
}
// the manifest: every file imported with type file, so a compiled binary
// carries it and a dev run reads it from disk
const files = walk(out).map((f) => relative(out, f).replaceAll("\\", "/")).sort();
const lines = ["// @ts-nocheck: generated by scripts/webbuild.ts, file imports of every dist file"];
lines.push(...files.map((f, i) => `import f${i} from "../dist/${f}" with { type: "file" };`));
lines.push("// a dist file's path on disk or in the binary");
lines.push(`export const files: Record<string, string> = {\n${files.map((f, i) => `  ${JSON.stringify(f)}: f${i},`).join("\n")}\n};`);
writeFileSync(join(dirname(out), "src", "manifest.ts"), lines.join("\n") + "\n");
log(`built the desktop's page, ${n} files precompressed, ${files.length} in the manifest`);

function walk(dir: string): string[] {
  const r: string[] = [];
  for (const e of readdirSync(dir)) {
    const p = join(dir, e);
    if (statSync(p).isDirectory()) r.push(...walk(p));
    else r.push(p);
  }
  return r;
}
