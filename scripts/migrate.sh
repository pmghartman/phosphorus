#!/bin/bash
# old install (phosphorus checkout, hesperus checkout or home) into a home: env, config, data, tailnet id
# usage: migrate.sh OLD_CHECKOUT HOME, the old tree kept
set -uo pipefail

main() {
  local old="${1:-}" home="${2:-}"
  say() { echo "[migrate] $*"; }
  fail() { echo "[migrate] ERROR: $*" >&2; exit 1; }
  [ -d "$old" ] && [ -d "$home" ] || fail "usage: migrate.sh OLD_CHECKOUT HOME"
  old="$(cd "$old" && pwd)" home="$(cd "$home" && pwd)"
  [ "$old" != "$home" ] || fail "old checkout and home are the same directory"
  [ -f "$old/.env" ] || fail "no .env in $old"
  [ -f "$home/.env" ] && fail "$home already has a .env, migrated before?"

  local docker=docker
  docker info >/dev/null 2>&1 || docker="sudo docker"

  # names by era: containers, volumes, ini, cli, ssh include
  local pre=phosphorus ini=phosphorus.ini c i
  # whichever container mounts this checkout names the era
  for c in $($docker ps -a --format '{{.Names}}' 2>/dev/null); do
    [ "$($docker inspect "$c" --format '{{range .Mounts}}{{if eq .Destination "/repo"}}{{.Source}}{{end}}{{end}}' 2>/dev/null)" = "$old" ] \
      && { pre="$c"; break; }
  done
  for i in phos.ini hesperus.ini; do [ -f "$old/config/$i" ] && ini=$i; done
  local clis=phos
  [ "$pre" = hesperus ] && clis="hesperus hesp"
  local project
  project="$($docker inspect "$pre" --format '{{index .Config.Labels "com.docker.compose.project"}}' 2>/dev/null)"
  [ -n "$project" ] || project="$(basename "$old" | tr 'A-Z' 'a-z' | tr -cd 'a-z0-9_-')"
  say "moving $old ($pre, compose project $project) into $home"

  # git first so a master hands off; never restarted by docker, kept for a rollback
  for c in "$pre-git" "$pre" "$pre-search" "$pre-updater"; do
    $docker inspect "$c" >/dev/null 2>&1 || continue
    say "stopping $c"
    echo "$c" >> "$home/.phosphorus-migrated-containers"
    $docker update --restart=no "$c" >/dev/null 2>&1
    $docker stop -t 30 "$c" >/dev/null 2>&1
    # same names as the new ones: removed, the volumes and data stay
    [ "$pre" = phosphorus ] && $docker rm "$c" >/dev/null 2>&1
  done
  # project sandboxes, recreated under the new names on resume
  local label=org.$pre.sandbox
  $docker ps -aq --filter "label=$label" | xargs -r $docker rm -f >/dev/null 2>&1
  case "$pre" in
    phosphorus) $docker network rm phos-sandbox >/dev/null 2>&1 ;;
    hesperus) $docker network rm hesperus-sandbox >/dev/null 2>&1 ;;
  esac

  # .env as it was, PHOS_ and HESPERUS_ renamed, games under the phosphorus zone
  # GIT_* (update.sh's private git host) dropped with their comment block
  awk '
    /^#/ || /^$/ { buf = buf $0 "\n"; next }
    /^GIT_(USERNAME|EMAIL|PASSWORD)=/ { buf = ""; next }
    { sub(/^(PHOS|HESPERUS)_/, "PHOSPHORUS_"); if (/^GAME_ZONE=/) $0 = "GAME_ZONE=phosphorus"; printf "%s%s\n", buf, $0; buf = "" }
    END { printf "%s", buf }
  ' "$old/.env" > "$home/.env" && chmod 600 "$home/.env" || fail "couldn't write $home/.env"
  grep -q '^GAME_ZONE=' "$home/.env" || echo 'GAME_ZONE=phosphorus' >> "$home/.env"

  mkdir -p "$home/config"
  [ -f "$old/config/services.export" ] && cp -p "$old/config/services.export" "$home/config/services.export"
  [ -f "$old/config/$ini" ] && cp -p "$old/config/$ini" "$home/config/phosphorus.ini"

  # the gguf hard-linked where the filesystem allows, the rest copied
  local d
  for d in state files git/data models; do
    [ -d "$old/$d" ] || continue
    say "copying $d"
    mkdir -p "$home/$d"
    { [ "$d" = models ] && cp -al "$old/$d/." "$home/$d/" 2>/dev/null; } \
      || cp -a "$old/$d/." "$home/$d/" || fail "couldn't copy $d"
  done
  # shares inside the checkout moved with it
  (cd "$home" && . "$home/scripts/lib/config.sh" && phosphorus_rehome_files "$old" all) || fail "couldn't move [files] dirs"
  # regenerated by the new frontend, the old paths in them
  rm -f "$home/state/ssh_config" "$home/state/machine.json"

  # tailnet identity: same node and ip, no auth key needed
  copy_volume "${project}_tailscale-state" phosphorus_tailscale-state
  copy_volume "$pre-git-data" phosphorus-git-data
  copy_volume "$pre-git-db" phosphorus-git-db
  copy_volume "$pre-models" phosphorus-models

  # the old cli links and ssh include, the new ones put back by bring-up
  local cli link
  for cli in $clis; do
    link=/usr/local/bin/$cli
    case "$(readlink "$link" 2>/dev/null)" in "$old"/*) rm -f "$link" 2>/dev/null || sudo rm -f "$link" ;; esac
  done
  local inc=/etc/ssh/ssh_config.d/$pre.conf
  grep -qs "$old/" "$inc" && { rm -f "$inc" 2>/dev/null || sudo rm -f "$inc"; }

  printf '%s\n' "$old" > "$home/.phosphorus-migrated-from"
  say "done, $old left as it was: delete it once phosphorus is up"
}

# $2's volume created from $1's, once, nothing when $1 doesn't exist
copy_volume() {
  $docker volume inspect "$1" >/dev/null 2>&1 || return 0
  [ "$1" = "$2" ] && return 0
  if $docker volume inspect "$2" >/dev/null 2>&1; then
    say "volume $2 already there, leaving it"
    return 0
  fi
  say "copying volume $1 to $2"
  $docker volume create "$2" >/dev/null || fail "couldn't create volume $2"
  $docker run --rm -v "$1:/from:ro" -v "$2:/to" alpine:3 cp -a /from/. /to/ \
    || fail "couldn't copy volume $1"
}

main "$@"
exit
